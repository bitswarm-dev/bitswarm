import { useSettings } from "@/features/settings/queries";
import { useNav } from "@/app/nav";
import { useUpdates } from "@/features/updates/queries";
import { useSchedules } from "@/features/schedules/queries";
import { useStats } from "@/features/torrents/queries";
import { formatBytes, formatKib, relativeTime } from "@/utils/format";

export function StatusBar() {
  const { data: stats } = useStats();
  const { data: set } = useSettings();
  const { data: rules } = useSchedules();
  const { data: upd } = useUpdates();
  const nav = useNav();
  const next = rules.filter((r) => r.enabled).sort((a, b) => a.nextRun - b.nextRun)[0];

  return (
    <footer className="status">
      {upd.state === "available" && upd.latest && (
        <button className="linkbtn" onClick={() => nav("/about")}>Update available: {upd.latest.version}</button>
      )}
      {stats.real ? (
        <span className="live">Listening on port {stats.port}</span>
      ) : (
        <span style={{ color: "var(--warn)" }} title="Torrents, peers and speeds are generated by the server. Nothing is downloaded.">
          Simulated engine
        </span>
      )}
      <span>
        DHT: {set.dht ? <><b className="num">{stats.dht}</b> nodes</> : "off"}
      </span>
      <span>
        Connections: <b className="num">{stats.conns}</b>
      </span>
      <span>
        Free space: <b className="num">{formatBytes(stats.free)}</b>
      </span>
      {stats.altActive ? (
        <span style={{ color: "var(--warn)" }}>
          Speed limit on{stats.alt ? "" : " (scheduled)"} · {formatKib(set.altDl)} ↓ · {formatKib(set.altUl)} ↑
        </span>
      ) : set.dlLimit || set.ulLimit ? (
        <span>
          Limits: {formatKib(set.dlLimit)} ↓ · {formatKib(set.ulLimit)} ↑
        </span>
      ) : null}
      {next && (
        <span>
          Next scheduled search: <b>{next.name}</b> <span className="num">{relativeTime(next.nextRun)}</span>
        </span>
      )}
    </footer>
  );
}
